const messages: Record<Locale, Record<TranslationKey, string>> = {
  'zh-CN': zhMessages,
  en: enMessages,
}

function normalizeLocale(locale?: string | null): Locale {
  if (String(locale || '').toLowerCase().startsWith('zh')) {
    return 'zh-CN'
  }
  return 'en'
}

function getInitialLocale(): Locale {
  if (typeof window === 'undefined') {
    return 'zh-CN'
  }

  const storedLocale = window.localStorage.getItem(LOCALE_STORAGE_KEY)
  if (storedLocale === 'zh-CN' || storedLocale === 'en') {
    return storedLocale
  }

  return normalizeLocale(window.navigator.language)
}

function applyLocale(locale: Locale) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale
  }
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale)
  }
}

const currentLocale = ref<Locale>(getInitialLocale())
applyLocale(currentLocale.value)

function interpolate(template: string, params?: Record<string, string | number>) {
  if (!params) {
    return template
  }

  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ''))
}

export function useI18n() {
  function setLocale(locale: Locale) {
    currentLocale.value = locale
    applyLocale(locale)
  }

  function toggleLocale() {
    setLocale(currentLocale.value === 'zh-CN' ? 'en' : 'zh-CN')
  }

  function t(key: TranslationKey, params?: Record<string, string | number>) {
    const template = messages[currentLocale.value][key] || enMessages[key] || key
    return interpolate(template, params)
  }

  return {
    locale: computed(() => currentLocale.value),
    isChinese: computed(() => currentLocale.value === 'zh-CN'),
    setLocale,
    toggleLocale,
    t,
  }
}
