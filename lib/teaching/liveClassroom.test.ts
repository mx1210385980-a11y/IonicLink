import assert from "node:assert/strict";
import { blankLiveRow, liveFields, liveRowsCsv } from "./liveFields";
import { liveCellMatches } from "./liveScoring";
import { scoreLive } from "./liveShared";
import { createLiveExperiment, finishLiveExperiment, finishLiveExtraction, getLiveDashboard, getLiveExperiment, getLiveStudent, joinLiveExperiment, prepareLiveSecondRound, saveLiveDraft, setLiveGold, setLivePaper, startLiveExperiment, startLiveExtraction, submitLive } from "./liveStore";
import { parseLiveTable } from "./liveTable";
import { liveTeachingExample } from "./liveExamples.server";

async function main() {
  assert.equal(liveFields("afm").length, 16);
  const conductivityCase = liveTeachingExample("conductivity")!, afmCase = liveTeachingExample("afm")!;
  assert.equal(conductivityCase.rows.length, 5); assert.equal(afmCase.rows.length, 16);
  assert(afmCase.rows.every((row) => row.temperature === "NR"), "DFT temperature is not an AFM measurement condition");
  assert.equal(afmCase.rows.find((row) => row.potential === "0 V")?.value, "0.47 nm");
  for (const example of [conductivityCase, afmCase]) assert.deepEqual(await parseLiveTable("example.csv", new TextEncoder().encode(liveRowsCsv(example.rows, example.domain)), example.domain), example.rows);
  const row = { ...Object.fromEntries(liveFields("afm").map((f) => [f.key, "NR"])), cation: "EMIM", anion: "TFSI", surface: "HOPG", property: "Layer spacing", value: "0.7 nm", evidence: "p. 4; Fig. 1A" };
  assert.deepEqual(await parseLiveTable("afm.csv", new TextEncoder().encode(liveRowsCsv([row], "afm")), "afm"), [row]);
  assert(liveCellMatches("anion", "TFSA", "[TFSI]"));
  assert(liveCellMatches("cation", "[EMIM]", "C2MIM"));
  assert(liveCellMatches("value", "1 nN", "1000 pN"));
  assert(!liveCellMatches("value", "1 pN", "0 pN"), "a fixed SI epsilon must not forgive a missing pN force");
  assert(!liveCellMatches("value", "1 nN", "1 N"));
  assert(liveCellMatches("value", "10 µF/cm²", "0.1 F/m2"));
  assert(!liveCellMatches("value", "10 µF/cm²", "10 µF/g"));
  const policy = { relativeTolerancePercent: 2, absoluteTolerance: "0.02 nN" };
  assert(liveCellMatches("value", "-1 nN", "-1.01 nN", policy));
  assert(liveCellMatches("value", "0 nN", "0.01 nN", policy));
  assert(!liveCellMatches("value", "-1 nN", "1 nN", policy));
  assert(!liveCellMatches("potential", "1 V", "1.01 V", policy), "tolerances must not relax experimental conditions");
  assert(!liveCellMatches("value", "NR", "0 nN", policy));
  assert(liveCellMatches("trend", "increases", "increasing"));
  assert(!liveCellMatches("trend", "increases", "decreases"));
  assert.equal(scoreLive([row], [{ ...row, value: "0.701 nm" }], {}, "afm", { relativeTolerancePercent: 1, absoluteTolerance: "" }).accuracy, 1);

  const lesson = createLiveExperiment({ name: "AFM classroom acceptance fixture", domain: "afm", groupCount: 2, channel: "alternating", classroomVersion: 2 });
  const first = joinLiveExperiment(lesson.id, { userKey: "a", alias: "A" });
  const second = joinLiveExperiment(lesson.id, { userKey: "b", alias: "B" });
  setLivePaper(lesson.id, { sourceId: "11111111-1111-1111-1111-111111111111", paperTitle: "Fixture 1" });
  assert.throws(() => startLiveExperiment(lesson.id), /answer key/);
  assert.throws(() => setLiveGold(lesson.id, [row], { assessmentPolicy: { relativeTolerancePercent: 2, absoluteTolerance: "9e999 nN" } }), /finite/);
  assert.throws(() => setLiveGold(lesson.id, [row], { assessmentPolicy: { relativeTolerancePercent: -1, absoluteTolerance: "" } }), /tolerance/);
  assert.throws(() => setLiveGold(lesson.id, [row], { assessmentPolicy: { relativeTolerancePercent: 1, absoluteTolerance: "0.1" } }), /unit/);
  assert.equal(getLiveExperiment(lesson.id).gold.length, 0, "invalid assessment settings cannot partially save a key");
  const version = getLiveExperiment(lesson.id).keyVersion!;
  setLiveGold(lesson.id, [row], { keyVersion: version, assessmentPolicy: policy, taskInstructions: "Read Figure 1A; retain the substrate and probe evidence." });
  assert.throws(() => setLiveGold(lesson.id, [row], { keyVersion: version }), /another session/);
  startLiveExperiment(lesson.id);
  const a = startLiveExtraction(first.id, 1);
  const recognized = finishLiveExtraction(first.id, a.version, [row], "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa");
  const sa = submitLive(first.id, { version: recognized.version, rows: [row] });
  const manual = saveLiveDraft(second.id, { version: 1, rows: [row] });
  assert.throws(() => submitLive(second.id, { version: manual.version, rows: [{ ...row, evidence: "" }] }), /Complete all/);
  submitLive(second.id, { version: manual.version, rows: [row] });
  assert.equal(getLiveStudent(first.id).participant.afmArtifactId, recognized.afmArtifactId);
  assert.match(getLiveStudent(first.id).experiment.taskInstructions || "", /Figure 1A/);
  const other = createLiveExperiment({ name: "Other class", domain: "conductivity", groupCount: 2 });
  assert.throws(() => joinLiveExperiment(other.id, { userKey: "a", alias: "A" }), /current classroom/);
  finishLiveExperiment(lesson.id);
  const next = prepareLiveSecondRound(lesson.id);
  assert.equal(prepareLiveSecondRound(lesson.id).id, next.id, "creating round 2 is idempotent");
  assert.equal(next.round, 2); assert.equal(next.gold.length, 0); assert.equal(next.paperSourceId, "");
  const roster = getLiveDashboard(next.id).participants;
  assert.deepEqual(roster.map((p) => [p.userKey, p.groupNo, p.mode]), [["a", 1, "manual"], ["b", 2, "ai"]]);
  assert(roster.every((p) => p.rows.length === 0 && !p.afmArtifactId));
  assert.equal(getLiveDashboard(lesson.id).participants[0].score?.accuracy, sa.score?.accuracy, "round 1 grades remain unchanged");
  assert.throws(() => setLivePaper(next.id, { sourceId: "11111111-1111-1111-1111-111111111111", paperTitle: "Same paper" }), /different paper/);
  setLivePaper(next.id, { sourceId: "22222222-2222-2222-2222-222222222222", paperTitle: "Fixture 2" });
  setLiveGold(next.id, [row]);
  setLivePaper(next.id, { sourceId: "33333333-3333-3333-3333-333333333333", paperTitle: "Replacement" });
  assert.equal(getLiveExperiment(next.id).gold.length, 0, "replacement papers clear stale answer keys");
  assert.throws(() => startLiveExperiment(next.id), /answer key/);
  setLiveGold(next.id, [row]); startLiveExperiment(next.id);
  assert.deepEqual(getLiveDashboard(next.id).participants.map((p) => [p.groupNo, p.mode]), [[1, "manual"], [2, "ai"]]);
  assert.equal(getLiveDashboard(next.id).previousRound?.experiment.id, lesson.id);
  assert.throws(() => prepareLiveSecondRound(next.id), /round 1/);
  assert.equal(blankLiveRow("afm").surface, "");
  console.log("Classroom readiness, physical units, assessment policy, source replacement and paired-round safeguards passed");
}
main();
